fn tool_def(name: &str, description: &str, input_schema: Value) -> Value {
    json!({
        "name": name,
        "description": description,
        "inputSchema": input_schema,
    })
}

fn extract_id_from_url(product: &str) -> String {
    let s = product.trim();
    if s.contains('/') {
        s.trim_end_matches('/')
            .rsplit('/')
            .next()
            .unwrap_or(s)
            .to_string()
    } else {
        s.to_string()
    }
}

