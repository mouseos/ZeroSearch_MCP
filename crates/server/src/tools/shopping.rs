use anyhow::Result;
use serde_json::{json, Value};

use super::args::{opt_i64, raw_str_param};
use crate::Providers;

fn product_param(args: &Value) -> String {
    let p = raw_str_param(args, "product");
    if p.is_empty() {
        raw_str_param(args, "product_id")
    } else {
        p
    }
}

fn str_or(args: &Value, key: &str, default: &str) -> String {
    let s = raw_str_param(args, key);
    if s.is_empty() {
        default.to_string()
    } else {
        s
    }
}

fn int_param(args: &Value, key: &str, default: i32) -> i32 {
    args.get(key)
        .and_then(|v| v.as_i64())
        .map(|v| v as i32)
        .unwrap_or(default)
}

fn opt_int(args: &Value, key: &str) -> Option<i32> {
    args.get(key).and_then(|v| v.as_i64()).map(|v| v as i32)
}

fn bool_param(args: &Value, key: &str, default: bool) -> bool {
    args.get(key).and_then(|v| v.as_bool()).unwrap_or(default)
}

fn opt_bool(args: &Value, key: &str) -> Option<bool> {
    args.get(key).and_then(|v| v.as_bool())
}

fn opt_f64(args: &Value, key: &str) -> Option<f64> {
    args.get(key).and_then(|v| v.as_f64())
}

fn opt_str(args: &Value, key: &str) -> Option<String> {
    let s = raw_str_param(args, key);
    if s.is_empty() {
        None
    } else {
        Some(s)
    }
}

fn int_array(args: &Value, key: &str) -> Vec<i64> {
    args.get(key)
        .and_then(|v| v.as_array())
        .map(|a| a.iter().filter_map(|v| v.as_i64()).collect())
        .unwrap_or_default()
}

fn str_array(args: &Value, key: &str) -> Vec<String> {
    args.get(key)
        .and_then(|v| v.as_array())
        .map(|a| {
            a.iter()
                .filter_map(|v| v.as_str().map(str::to_string))
                .collect()
        })
        .unwrap_or_default()
}

pub fn tool_definitions() -> Vec<Value> {
    DEFS.clone()
}

/// The tool definitions, kept as data (`defs/shopping.json`) and
/// parsed once: building them with `json!` compiled to hundreds of
/// KiB of machine code for what is a constant document.
static DEFS: std::sync::LazyLock<Vec<Value>> =
    std::sync::LazyLock::new(|| super::parse_defs(include_str!("defs/shopping.json")));

fn extract_id_from_url(product: &str) -> String {
    let s = product.trim();
    if s.contains('/') {
        s.trim_end_matches('/')
            .rsplit('/')
            .next()
            .unwrap_or(s)
            .to_string()
    } else {
        s.to_string()
    }
}

